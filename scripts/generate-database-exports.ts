import { parse } from "@babel/parser";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** Forward the pinned ORM's wildcard exports without copying its implementation. */
export async function generateDatabaseExports(output: string, check = false) {
  const upstream = dirname(fileURLToPath(import.meta.resolve("drizzle-orm")));
  const manifest = JSON.parse(await readFile(join(upstream, "package.json"), "utf8"));
  if (
    Object.keys(manifest.exports).some((key) => key !== "." && key !== "./*") ||
    manifest.exports["."]?.import?.default !== "./index.js" ||
    manifest.exports["./*"]?.import?.default !== "./*.js" ||
    manifest.exports["./*"]?.import?.types !== "./*.d.ts"
  )
    throw new Error("Drizzle's export layout changed; update the database forwarding generator.");
  const modules = [...new Bun.Glob("**/*.js").scanSync({ cwd: upstream, onlyFiles: true })]
    .filter((name) => !name.split("/").includes("node_modules"))
    .sort();
  const expected = new Map<string, string>();
  for (const module of modules) {
    const name = module.slice(0, -3);
    const source = await readFile(join(upstream, module), "utf8");
    const ast = parse(source, { sourceType: "module" });
    const hasDefault = ast.program.body.some(
      (node) =>
        node.type === "ExportDefaultDeclaration" ||
        (node.type === "ExportNamedDeclaration" &&
          node.specifiers.some(
            (specifier) =>
              (specifier.exported.type === "Identifier"
                ? specifier.exported.name
                : specifier.exported.value) === "default",
          )),
    );
    const target = JSON.stringify(`drizzle-orm/${name}`);
    const forwarding = `// Generated by scripts/generate-database-exports.ts.\nexport * from ${target};\n${hasDefault ? `export { default } from ${target};\n` : ""}`;
    expected.set(`${name}.js`, forwarding);
    expected.set(`${name}.d.ts`, forwarding);
  }
  if (check) {
    const actual = (await readdir(output, { recursive: true, withFileTypes: true }))
      .filter((entry) => entry.isFile())
      .map((entry) => relative(output, join(entry.parentPath, entry.name)))
      .sort();
    if (JSON.stringify(actual) !== JSON.stringify([...expected.keys()].sort()))
      throw new Error("Database forwarding files are stale. Run bun run database:exports.");
    for (const [path, content] of expected)
      if ((await readFile(join(output, path), "utf8")) !== content)
        throw new Error(`Stale database forwarding file: ${path}. Run bun run database:exports.`);
  } else {
    await rm(output, { recursive: true, force: true });
    for (const [path, content] of expected) {
      await mkdir(dirname(join(output, path)), { recursive: true });
      await writeFile(join(output, path), content);
    }
  }
  return modules.length;
}

if (import.meta.main) {
  const count = await generateDatabaseExports(
    resolve("src/database/generated"),
    process.argv.includes("--check"),
  );
  console.log(
    `${count} Drizzle entry points ${process.argv.includes("--check") ? "verified" : "forwarded"}.`,
  );
}
